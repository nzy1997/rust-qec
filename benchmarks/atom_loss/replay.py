"""Re-export each archived corpus with the specified generator, without decoding."""
import argparse
import hashlib
import json
from pathlib import Path
import tempfile
import zipfile
from .run import ROOT, checked, generate, logical_x
from .shot_data import cases_from, validate_dataset


def replay(archive, binary):
    checked_cases=[]
    with zipfile.ZipFile(archive) as z, tempfile.TemporaryDirectory() as tmp:
        cases=([(f"{c['setting']}-s{c['seed']}",c) for c in json.loads(z.read('accuracy-seeds.json'))['cases']]
               if 'accuracy-seeds.json' in z.namelist() else cases_from(z.read))
        for label,case in cases:
            read=lambda n:z.read(f'{label}/{n}')
            validate_dataset(read,case)
            work=Path(tmp)/label;work.mkdir();circuit=work/'circuit.stim'
            generate(binary,circuit,case['distance'],case['rounds'],case['loss_probability'],case['pauli_probability'])
            if circuit.read_bytes()!=read('public/circuit.stim'): raise ValueError('Regenerated circuit mismatch: '+label)
            generation=json.loads(read('private/manifest.json'))['generation']
            if generation['batch_shots']!=10000: raise ValueError('Unsupported CLI batch size')
            checked([binary,'dataset','export','--circuit',circuit,'--shots',case['shots'],
                     '--seed',case['seed'],
                     '--mode','measurements_blinded','--logical-x-qubits',logical_x(circuit.read_text(),case['distance']),
                     '--public-out',work/'public','--private-out',work/'private'])
            for member in ['public/shots.b8','private/masks.b8','private/answers.b8']:
                if (work/member).read_bytes()!=read(member): raise ValueError('Regenerated bytes mismatch: '+label+'/'+member)
            checked_cases.append(label)
            print(label+': deterministic circuit, public rows, masks and answers match',flush=True)
    return checked_cases


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--archive',type=Path,default=ROOT/'site/static/data/atom-loss/shot-data-v1.zip')
    p.add_argument('--binary',type=Path,default=ROOT/'target/release/rustqec');args=p.parse_args()
    print('PASS:',len(replay(args.archive,args.binary)),'corpora')
